import Foundation

public struct HostsEntry: Hashable, Sendable, Codable {
    public var address: IPAddress
    public var hostnames: [String]

    public init(address: IPAddress, hostnames: [String]) {
        self.address = address
        self.hostnames = hostnames
    }
}

public enum HostsFileError: Error, LocalizedError, Equatable, Sendable {
    case unterminatedBlock(line: Int)
    case endWithoutBegin(line: Int)
    case multipleBlocks
    case invalidEntry(String)
    case notUTF8

    public var errorDescription: String? {
        switch self {
        case .unterminatedBlock(let l):
            return "The DNS Redirect section in /etc/hosts starts at line \(l) but has no end marker. Fix it by hand, then try again. The app will not edit a damaged section."
        case .endWithoutBegin(let l):
            return "/etc/hosts has a DNS Redirect end marker at line \(l) with no start marker. Fix it by hand, then try again."
        case .multipleBlocks:
            return "/etc/hosts contains more than one DNS Redirect section. Remove the duplicates by hand, then try again."
        case .invalidEntry(let m):
            return "Refusing to write an invalid hosts entry: \(m)"
        case .notUTF8:
            return "/etc/hosts is not valid UTF-8 text."
        }
    }
}

/// Reads and edits the application-owned section of a hosts file. Everything outside the
/// markers is preserved byte-for-byte.
public enum ManagedHostsBlock {
    public static let beginMarker = "# >>> DNS Redirect managed section — do not edit >>>"
    public static let endMarker = "# <<< DNS Redirect managed section <<<"
    public static let headerComment = "# Rules in this section are generated by DNS Redirect.app and replaced on every apply."
    public static let maxHostnamesPerLine = 6

    /// Line indices of the block markers, or nil if no block exists.
    public static func locate(in content: String) throws -> ClosedRange<Int>? {
        let lines = content.components(separatedBy: "\n")
        var begin: Int?
        var found: ClosedRange<Int>?
        for (i, raw) in lines.enumerated() {
            let line = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if line == beginMarker {
                if begin != nil { throw HostsFileError.unterminatedBlock(line: begin! + 1) }
                if found != nil { throw HostsFileError.multipleBlocks }
                begin = i
            } else if line == endMarker {
                guard let b = begin else { throw HostsFileError.endWithoutBegin(line: i + 1) }
                found = b...i
                begin = nil
            }
        }
        if let b = begin { throw HostsFileError.unterminatedBlock(line: b + 1) }
        return found
    }

    /// Validates entries and renders the managed block (including markers, no trailing newline).
    public static func render(entries: [HostsEntry]) throws -> [String] {
        var lines = [beginMarker, headerComment]
        for entry in entries {
            guard !entry.hostnames.isEmpty else { continue }
            for host in entry.hostnames {
                do { try DomainName.validate(host) } catch {
                    throw HostsFileError.invalidEntry("\(host): \(error.localizedDescription)")
                }
            }
            var start = 0
            while start < entry.hostnames.count {
                let chunk = entry.hostnames[start..<min(start + maxHostnamesPerLine, entry.hostnames.count)]
                lines.append("\(entry.address)\t\(chunk.joined(separator: " "))")
                start += maxHostnamesPerLine
            }
        }
        lines.append(endMarker)
        return lines
    }

    /// Returns new file content with the managed block replaced by `entries`.
    /// An empty `entries` array removes the block completely.
    public static func applying(_ entries: [HostsEntry], to content: String) throws -> String {
        let hasEntries = entries.contains { !$0.hostnames.isEmpty }
        var lines = content.components(separatedBy: "\n")
        if let range = try locate(in: content) {
            if hasEntries {
                lines.replaceSubrange(range, with: try render(entries: entries))
            } else {
                lines.removeSubrange(range)
            }
            return lines.joined(separator: "\n")
        }
        guard hasEntries else { return content }
        var result = content
        if !result.isEmpty && !result.hasSuffix("\n") { result += "\n" }
        result += try render(entries: entries).joined(separator: "\n") + "\n"
        return result
    }

    public static func removing(from content: String) throws -> String {
        try applying([], to: content)
    }

    /// Entries currently inside the managed block.
    public static func managedEntries(in content: String) throws -> [HostsEntry] {
        guard let range = try locate(in: content) else { return [] }
        let lines = content.components(separatedBy: "\n")
        return lines[range].compactMap(parseLine)
    }

    /// hostname → addresses for every mapping *outside* the managed block.
    public static func unmanagedMappings(in content: String) -> [String: [IPAddress]] {
        var lines = content.components(separatedBy: "\n")
        if let range = try? locate(in: content) { lines.removeSubrange(range) }
        return mappings(from: lines.compactMap(parseLine))
    }

    public static func mappings(from entries: [HostsEntry]) -> [String: [IPAddress]] {
        var map: [String: [IPAddress]] = [:]
        for e in entries {
            for h in e.hostnames where !(map[h]?.contains(e.address) ?? false) {
                map[h, default: []].append(e.address)
            }
        }
        return map
    }

    /// Parses a single hosts(5) line. Comments and blank lines return nil.
    public static func parseLine(_ raw: String) -> HostsEntry? {
        var line = Substring(raw)
        if let hash = line.firstIndex(of: "#") { line = line[..<hash] }
        let fields = line.split(whereSeparator: { $0 == " " || $0 == "\t" || $0 == "\r" })
        guard fields.count >= 2, let ip = IPAddress(String(fields[0])) else { return nil }
        return HostsEntry(address: ip, hostnames: fields.dropFirst().map { $0.lowercased() })
    }
}
